"""standards/ci/check-commits.sh on throwaway repositories (DEV-4.1 to DEV-4.5)."""

from __future__ import annotations

import os
import subprocess
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parents[2] / "standards" / "ci" / "check-commits.sh"
AUTHOR = "git@debever.pl"


def _git(repo: Path, *args: str, email: str = AUTHOR) -> None:
    env = {
        **os.environ,
        "GIT_AUTHOR_NAME": "Daldek",
        "GIT_AUTHOR_EMAIL": email,
        "GIT_COMMITTER_NAME": "Daldek",
        "GIT_COMMITTER_EMAIL": email,
    }
    subprocess.run(["git", "-C", str(repo), *args], check=True, env=env)


@pytest.fixture
def repo(tmp_path: Path) -> Path:
    subprocess.run(["git", "init", "-q", str(tmp_path)], check=True)
    _git(tmp_path, "commit", "-q", "--allow-empty", "-m", "chore: root")
    return tmp_path


def _check(
    repo: Path, message: str, email: str = AUTHOR
) -> subprocess.CompletedProcess[str]:
    _git(repo, "commit", "-q", "--allow-empty", "-m", message, email=email)
    return subprocess.run(
        ["bash", str(SCRIPT)],
        cwd=repo,
        env={**os.environ, "GATE_COMMIT_RANGE": "HEAD^!"},
        capture_output=True,
        text=True,
    )


@pytest.mark.parametrize(
    "message",
    [
        "feat(cli): add drift --strict",
        'Revert "feat: add x"\n\nThis reverts commit abc.',
        "fix: x\n\nCo-authored-by: Jan Gemini <jan@gemini.pl>",
        "fix: x\n\nGenerated by the cursor handler in gpt-lib.",
        "docs: explain how Claude Code reads CLAUDE.md",
    ],
)
def test_check_commits_accepts_message(repo: Path, message: str) -> None:
    done = _check(repo, message)
    assert done.returncode == 0, done.stdout + done.stderr


@pytest.mark.parametrize(
    ("message", "rule"),
    [
        ("Add drift", "DEV-4.1"),
        ("Revert drift", "DEV-4.1"),
        ("fix: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>", "DEV-4.3"),
        ("fix: x\n\nCo-authored-by: Devin <devin@cognition.ai>", "DEV-4.3"),
        (
            "fix: x\n\nCo-authored-by: Copilot "
            "<175728472+Copilot@users.noreply.github.com>",
            "DEV-4.3",
        ),
        (
            "fix: x\n\nCo-authored-by: Bot <x+devin-ai-integration[bot]"
            "@users.noreply.github.com>",
            "DEV-4.3",
        ),
        ("fix: x\n\n🤖 Generated with [Claude Code](https://claude.com)", "DEV-4.3"),
        ("fix: x\n\nGenerated with Aider", "DEV-4.3"),
        ("fix: x\n\nClaude-Session: abc", "DEV-4.3"),
    ],
)
def test_check_commits_rejects_message(repo: Path, message: str, rule: str) -> None:
    done = _check(repo, message)
    assert done.returncode == 1
    assert rule in done.stdout


def test_check_commits_rejects_other_author(repo: Path) -> None:
    done = _check(repo, "fix: x", email="agent@local")
    assert done.returncode == 1
    assert "DEV-4.2" in done.stdout
